import type { JSX } from 'react'
import { cn } from '@/lib/utils'
import type { StreamingLinks } from '@/lib/data'

type Platform = 'spotify' | 'apple' | 'soundcloud' | 'youtube'

const platforms: {
  key: Platform
  label: string
  Icon: ({ className }: { className?: string }) => JSX.Element
}[] = [
  { key: 'spotify', label: 'Spotify', Icon: SpotifyIcon },
  { key: 'apple', label: 'Apple Music', Icon: AppleMusicIcon },
  { key: 'soundcloud', label: 'SoundCloud', Icon: SoundCloudIcon },
  { key: 'youtube', label: 'YouTube', Icon: YouTubeIcon },
]

interface StreamingIconRowProps {
  links: StreamingLinks
  className?: string
  iconClassName?: string
}

export function StreamingIconRow({ links, className, iconClassName }: StreamingIconRowProps) {
  const available = platforms.filter((p) => links[p.key])

  if (available.length === 0) return null

  return (
    <div className={cn('flex items-center gap-1', className)} onClick={(e) => e.stopPropagation()}>
      {available.map(({ key, label, Icon }) => (
        <a
          key={key}
          href={links[key]}
          target="_blank"
          rel="noopener noreferrer"
          data-cursor-label="LISTEN"
          aria-label={`Listen on ${label}`}
          className={cn(
            'p-2 text-white/50 transition-smooth hover:text-white',
            iconClassName,
          )}
        >
          <Icon className="size-4" />
        </a>
      ))}
    </div>
  )
}

export function hasStreamingLinks(links: StreamingLinks) {
  return platforms.some((p) => Boolean(links[p.key]))
}

